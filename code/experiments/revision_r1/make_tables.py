#!/usr/bin/env python3
"""Turn the E1-E5 CSVs into RESULTS.md and LaTeX table fragments (tables/*.tex).

The manuscript \\input{}s nothing from here (the portal needs a flat source), but
every number quoted in main-cssp.tex and in the response is copied from these
fragments, never typed from memory.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
T = HERE / "tables"
T.mkdir(exist_ok=True)
NAMES = {
    "gaussian_control": "Gaussian control",
    "centered_exponential_skew": "Centered exponential",
    "uniform_platykurtic": "Uniform",
    "symmetric_contaminated": "Symmetric contaminated",
}
md = ["# CSSP-R1 new results (generated by make_tables.py)", ""]


def sci(x: float) -> str:
    if x == 0:
        return "0"
    e = int(np.floor(np.log10(abs(x))))
    m = x / 10**e
    if -2 <= e <= 2:
        return f"{x:.3g}"
    return f"${m:.2f}\\times10^{{{e}}}$"


# ---------------- E1
e1 = pd.read_csv(HERE / "e1_colored_input.csv")
md += ["## E1 colored input (AR(1) Gaussian copula, marginal fixed; d=3, s=2, n=2500, 150 reps)", ""]
md += [e1[["regime", "phi", "marginal_skew", "gram_offdiag_rel", "oracle_vwk_mse", "wiener_mse",
           "vwk_full_ls_mse", "W_over_oracle", "oracle_over_ls"]].to_markdown(index=False, floatfmt=".4g"), ""]
lines = [r"\begin{tabular}{@{}lrrrrrrr@{}}", r"\toprule",
         r"Regime & $\phi$ & $\|\hat G-I\|_F/\sqrt{p}$ & Oracle VWK & Wiener & Full LS (VWK) & $W/\mathrm{oracle}$ & oracle/LS \\",
         r"\midrule"]
for reg in ["centered_exponential_skew", "gaussian_control"]:
    g = e1[e1.regime == reg]
    for k, r in enumerate(g.itertuples()):
        name = NAMES[reg] if k == 0 else ""
        lines.append(f"{name} & {r.phi:.1f} & {r.gram_offdiag_rel:.3f} & {r.oracle_vwk_mse:.4f} & {r.wiener_mse:.4f} & "
                     f"{r.vwk_full_ls_mse:.5f} & {r.W_over_oracle:.3f} & {r.oracle_over_ls:.0f} \\\\")
    lines.append(r"\midrule")
lines[-1] = r"\bottomrule"
lines.append(r"\end{tabular}")
(T / "e1_colored.tex").write_text("\n".join(lines) + "\n")

# ---------------- E2
e2 = pd.read_csv(HERE / "e2_moment_sensitivity.csv")
md += ["## E2 empirical-basis error, degree x n (d=1, 200 reps). orth = max|<psi_i,psi_j>_P - delta| under the TRUE law; relerr = median relative signal error of the empirical-basis projection vs the oracle-basis projection", ""]
for reg, g in e2.groupby("regime"):
    md += [f"### {NAMES[reg]}", "orth_err_median:", g.pivot(index="order", columns="n", values="orth_err_median").to_markdown(floatfmt=".3g"),
           "", "rel_signal_err median:", g.pivot(index="order", columns="n", values="rel_signal_err_emp_vs_oracle_median").to_markdown(floatfmt=".3f"), ""]
fits = {}
for reg, g in e2.groupby("regime"):
    X = np.c_[np.ones(len(g)), g.order, np.log10(g.n)]
    b = np.linalg.lstsq(X, np.log10(g.orth_err_median), rcond=None)[0]
    need = {}
    for s, gs in g.groupby("order"):
        ok = gs[gs.rel_signal_err_emp_vs_oracle_median <= 0.05]
        need[s] = int(ok.n.min()) if len(ok) else None
    fits[reg] = (10 ** b[1], b[2], need)
    md += [f"- {NAMES[reg]}: orth error grows x{10**b[1]:.1f} per degree, n-exponent {b[2]:.2f}; smallest n with relerr<=5%: {need}"]
md += [""]
# LaTeX: relerr table for the exponential and Gaussian rows, plus the 5% line
lines = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
         r"Regime & $s$ & $n=250$ & $500$ & $1000$ & $2500$ & $5000$ & $20000$ \\", r"\midrule"]
for reg in ["centered_exponential_skew", "gaussian_control", "uniform_platykurtic"]:
    g = e2[e2.regime == reg]
    for k, s in enumerate(sorted(g.order.unique())):
        gs = g[g.order == s].sort_values("n")
        name = NAMES[reg] if k == 0 else ""
        vals = " & ".join(f"{v:.3f}" if v < 1 else f"{v:.2f}" for v in gs.rel_signal_err_emp_vs_oracle_median)
        lines.append(f"{name} & {s} & {vals} \\\\")
    lines.append(r"\midrule")
lines[-1] = r"\bottomrule"
lines.append(r"\end{tabular}")
(T / "e2_relerr.tex").write_text("\n".join(lines) + "\n")
lines = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
         r"Regime & $s$ & $n=250$ & $500$ & $1000$ & $2500$ & $5000$ & $20000$ \\", r"\midrule"]
for reg in ["centered_exponential_skew", "gaussian_control", "uniform_platykurtic"]:
    g = e2[e2.regime == reg]
    for k, s in enumerate(sorted(g.order.unique())):
        gs = g[g.order == s].sort_values("n")
        name = NAMES[reg] if k == 0 else ""
        vals = " & ".join(sci(v) for v in gs.orth_err_median)
        lines.append(f"{name} & {s} & {vals} \\\\")
    lines.append(r"\midrule")
lines[-1] = r"\bottomrule"
lines.append(r"\end{tabular}")
(T / "e2_orth.tex").write_text("\n".join(lines) + "\n")

# ---------------- E3
e3 = pd.read_csv(HERE / "e3_law_mismatch.csv")
md += ["## E3 law mismatch (centered-exponential base; d=3, s=2, n=2500, 150 reps)", "",
       e3.to_markdown(index=False, floatfmt=".4g"), ""]
lines = [r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
         r"Perturbation & level & Mismatched VWK & Correct VWK & Wiener & Monomial LS & cond (VWK) & cond (monomial) \\", r"\midrule"]
for r in e3.itertuples():
    fam = "$\\varepsilon$-contamination" if r.family == "contamination" else "$\\mu_3$ mis-set"
    lev = f"$\\varepsilon={r.param:.2f}$" if r.family == "contamination" else f"$\\times{r.param:.1f}$"
    lines.append(f"{fam} & {lev} & {r.mismatched_vwk_mse:.4f} & {r.correct_vwk_mse:.4f} & {r.wiener_mse:.4f} & "
                 f"{r.monomial_ls_mse:.5f} & {r.cond_mismatched_vwk_gram:.2f} & {r.cond_monomial_gram:.1f} \\\\")
lines += [r"\bottomrule", r"\end{tabular}"]
(T / "e3_mismatch.tex").write_text("\n".join(lines) + "\n")

# ---------------- E4
e4 = pd.read_csv(HERE / "e4_output_noise.csv")
p = 10
e4["noiseproj_bias_over_null"] = e4.noiseproj_bias_norm / (e4.noiseproj_sd_rms / np.sqrt(150) * np.sqrt(p))
md += ["## E4 output-noise law (matched sd 0.25; d=3, s=2, n=2500, 150 reps). noiseproj = E_n[eps Psi_alpha]; bias_over_null = ||mean||/(se*sqrt(p)), ~1 under H0", "",
       e4[["regime", "noise_law", "oracle_vwk_mse", "W_over_oracle", "noiseproj_bias_norm", "noiseproj_sd_rms",
           "noiseproj_sd_theory_iid", "noiseproj_bias_over_null"]].to_markdown(index=False, floatfmt=".4g"), ""]
lines = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
         r"Input regime & Output-noise law & Oracle VWK & $W/\mathrm{oracle}$ & $\|\overline{\hat a_\varepsilon}\|$ & sd$(\hat a_\varepsilon)$ & $\sigma_\varepsilon/\sqrt{n}$ \\", r"\midrule"]
LAW = {"gaussian": "Gaussian", "centered_exponential": "Centered exponential", "student_t3": "Student $t_3$", "contaminated_10pct": "10\\% contaminated"}
for reg in ["centered_exponential_skew", "gaussian_control"]:
    g = e4[e4.regime == reg]
    for k, r in enumerate(g.itertuples()):
        name = NAMES[reg] if k == 0 else ""
        lines.append(f"{name} & {LAW[r.noise_law]} & {r.oracle_vwk_mse:.4f} & {r.W_over_oracle:.2f} & "
                     f"{r.noiseproj_bias_norm:.4f} & {r.noiseproj_sd_rms:.4f} & {r.noiseproj_sd_theory_iid:.4f} \\\\")
    lines.append(r"\midrule")
lines[-1] = r"\bottomrule"
lines.append(r"\end{tabular}")
(T / "e4_noise.tex").write_text("\n".join(lines) + "\n")

# ---------------- E5
e5 = pd.read_csv(HERE / "e5_streaming.csv")
md += ["## E5 streaming (centered exponential, d=3, s=2, n=50000, refresh K=500)", "", e5.to_markdown(index=False, floatfmt=".4g"), ""]

(HERE / "RESULTS.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
